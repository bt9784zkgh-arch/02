from content import PAGES as SAMPLE

import re as _re
def sample(title_part):
    for p in SAMPLE:
        plain = _re.sub(r"\{([^|{}]+)\|[^{}]+\}", r"\1", p.get("title", ""))
        if title_part in plain:
            return p
    raise KeyError(title_part)

def P(cat, icon, title, goal, *blocks, reflect=True):
    b = list(blocks) + ([{"t": "reflect"}] if reflect else [])
    return {"cat": cat, "icon": icon, "title": title, "goal": goal, "blocks": b}

def S(kind, text): return {"t": "step", "kind": kind, "text": text}
def H(text, title=None):
    d = {"t": "hint", "text": text}
    if title: d["title"] = title
    return d
def T(text): return {"t": "talk", "text": text}
def L(starter="わたしは、", n=2): return {"t": "lines", "starter": starter, "n": n}
def C(items, cols=1): return {"t": "choices", "items": items, "cols": cols}
def SC(text, svg="think", img=None, msg=None):
    d = {"t": "scene", "svg": svg, "text": text}
    if img: d["img"] = img
    if msg: d["msg"] = msg
    return d
def ORD(items): return {"t": "order", "items": items}
def TB(head, rows, w=None, h=None, cls=""):
    return {"t": "table", "head": head, "rows": rows, "w": w, "h": h, "cls": cls}
def IM(files, num=True, h=38, caps=None): return {"t": "imgs", "files": files, "num": num, "h": h, "caps": caps}

ASK = "あなたなら どうする？ いちばん 近い ものに ○を 1つ つけよう。"

def D(cat, icon, title, scene, choices, hint, svg="think", img=None, cols=1, ask=ASK, goal=None, reason=True):
    """「どうすればいい？」の形"""
    blocks = [SC(scene, svg, img), S("えらぶ", ask), C(choices, cols)]
    if reason:
        blocks += [S("かく", "そう えらんだ わけを 書こう。"), L("なぜなら、", 1)]
    blocks += [H(hint)]
    return P(cat, icon, title, goal or "こまった とき、どう 動くか 考えよう。", *blocks)

def RANK(cat, icon, title, goal, ask, items, after, hint, talk=None):
    blocks = [S("かく", ask), ORD(items), S("かく", after), L("いちばんは ＿＿ です。なぜなら、", 1)]
    if talk: blocks.append(T(talk))
    blocks.append(H(hint))
    return P(cat, icon, title, goal, *blocks)

