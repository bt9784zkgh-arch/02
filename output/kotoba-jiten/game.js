  /* --- 問題を出す --- */
  function startQuestions() { S.phase = 'q'; S.qi = 0; showQuestion(); }
  function showQuestion() {
    const st = S.st, step = S.step, qd = st['step' + step].questions[S.qi];
    S.tries = 0; S.solved = false; S.busy = false;
    clearFloat();
    if (step === 1) {
      const choices = qd.cards.map((id, i) => Object.assign(exampleChoice(id), { praise: qd.praise[i], taken: false }));
      renderQuestion({ ask: ask1(), choices, neutral: false, thoughtCards: !!st.thought });
      say(T.start1, '', 'normal');
      armFloat();
    } else if (step === 2) {
      const ok = exampleChoice(qd.ok, qd.okText); const ng = ngChoice(qd.ng, qd.ngArt);
      const choices = place(ok, [ng], POS2[S.qi % POS2.length]);
      renderQuestion(Object.assign(thoughtFor(ok, null), { ask: st.ask2, choices, neutral: true, thoughtCards: false }));
      say(T.start2, '', 'normal');
    } else {
      const ok = exampleChoice(qd.ok, qd.okText); const ngs = qd.ng.map((x) => ngChoice(x));
      const choices = place(ok, ngs, POS3[S.qi % POS3.length]);
      const q = { scene: qd.scene, sceneArt: qd.sceneArt, ask: T.ask3, choices, neutral: true, thoughtCards: false };
      renderQuestion(q);
      say(T.start3, '', 'normal');
    }
  }

