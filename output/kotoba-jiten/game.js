  function exampleChoice(ref, text) { // ID または {id,text,art} または 文
    const st = S.st;
    if (typeof ref === 'string' && st.cardMap[ref]) {
      const c = st.cardMap[ref];
      return { id: c.id, text: text || c.text, nk: c.nk, art: c.art, thought: c.thought, ok: true };
    }
    if (ref && typeof ref === 'object') {
      if (ref.id && st.cardMap[ref.id]) return Object.assign(exampleChoice(ref.id, ref.text || text), ref.art ? { art: artList(ref.art) } : {});
      return { id: null, text: ref.text, nk: ref.nk || 0, art: ref.art ? artList(ref.art) : autoArt(ref.text, false), thought: null, ok: true };
    }
    return { id: null, text: String(ref), nk: 0, art: autoArt(ref, false), thought: null, ok: true };
  }
