  async function solve(c, el, together) {
    S.busy = true; S.solved = true;
    const run = RUN;
    els.qscene.classList.remove('is-emph');
    markCorrect(el, c, true);
    const qd = S.st['step' + S.step].questions[S.qi];
    say(qd.praise, 'praise', 'normal');
    autoSpeak([c.text, qd.praise]);
    renderProgress();
    try {
      await wait(600, run);
      hidePointer();
      if (c.id) { flyCard(el, () => collect(c.id)); await wait(760, run); }
      S.busy = false;
      els.next.classList.remove('is-hidden');
      focusLater(els.next);
    } catch (e) { if (e !== ABORT) throw e; }
    void together;
  }

  async function miss(c, el) {
    S.tries++;
    SND.play('retry');
    M3.encourage();
    const qd = S.st['step' + S.step].questions[S.qi];
    const okIdx = S.choices.findIndex((x) => x.ok);
    const okEl = S.cardEls[okIdx];
    if (S.tries === 1) {
      el.classList.add('is-retry');
      els.qscene.classList.add('is-emph');           // ヒントの絵を少し強調
      const msg = c.retry || T.retry;
      say(msg, 'retry', 'normal');
      autoSpeak([msg]);
    } else if (S.tries === 2) {
      el.classList.add('is-retry');
      okEl.classList.add('is-hint');                 // 正解がゆっくりふくらんで光る
      if (S.choices.length > 2) el.classList.add('is-out'); // 3まいのときは2まいにしぼる
      const msg = qd.hint || T.retry;            // 2回目は、特別なことばがあっても ふつうのヒントへ
      say(msg, 'retry', 'think');
      autoSpeak([msg]);
    } else {
      S.busy = true;
      const run = RUN;
      say(T.together, '', 'think');
      autoSpeak([T.together]);
      okEl.classList.add('is-hint');
      try {
        await pointTo(okEl, run);
        await wait(500, run);
        S.busy = false;
        solve(S.choices[okIdx], okEl, true);
      } catch (e) { if (e !== ABORT) throw e; }
    }
  }

