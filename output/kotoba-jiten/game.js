  function showReview() {
    const st = S.st;
    if (!DATA.done.includes(st.no)) DATA.done.push(st.no);
    delete DATA.resume[st.no];
    save();
    const all = DATA.done.length >= 8;
    $('#rev-tab').className = 'stage-tab cloth bk-' + st.no;
    const tab = $('#rev-tab-slip');
    tab.innerHTML = ruby(st.long ? st.shelf : st.word);
    tab.style.fontSize = st.long ? '28px' : '';
    tab.style.lineHeight = st.long ? '1.55' : '';
    $('#review-page').className = 'review-page paper bk-' + st.no;
    $('#rev-title').innerHTML = ruby(all ? T.reviewAllTitle : T.reviewTitle);
    const meaning = st.word + ' とは、' + st.meaning;
    $('#rev-meaning').innerHTML = ruby(meaning);
    const checks = [
      all ? T.check1All : fill(T.check1, st.total),
      st.check2 || ('『' + st.word + '』に {合|あ}う {行動|こうどう}を {選|えら}べた'),
      T.check3
    ];
    $('#rev-checks').innerHTML = checks.map((c) =>
      '<li class="check-item"><svg class="motif" aria-hidden="true"><use href="#m-i-check"/></svg><span>' + ruby(c) + '</span></li>').join('');
    $('#rev-last').innerHTML = ruby(st.last);
    $('#rev-pick-label').innerHTML = ruby(T.tryIt) + '<br>' + ruby(T.pick);
    S.picked = null;
    renderPick(false);
    show('review');
    SND.play('review');
    const title = all ? T.reviewAllTitle + ' ' + T.check1All : T.reviewTitle + '『' + st.word + '』の ページが できた';
    autoSpeak([title, meaning]);
    focusLater($('#rev-end'));
  }
